def _align_comments(text: str, col: int = 46) -> str:
    """Align the trailing '# ...' comments of the INPUTS block (section 1) for readability."""
    head, sep, rest = text.partition("# 1. INPUTS")
    block, sep2, tail = rest.partition("# derived")
    out = []
    for ln in block.split("\n"):
        if "  # " in ln and not ln.lstrip().startswith("#"):
            code, _, com = ln.partition("  # ")
            ln = code.rstrip().ljust(col) + "# " + com
        out.append(ln)
    return head + sep + "\n".join(out) + sep2 + tail


def _g(x: float) -> str:
    return repr(float(x))


def generate_script(cfgs: list[MEConfig], script_name: str = "me_cooling_standalone.py",
                    version: str = "", lut_name: str = "lut_current_rf_1-10nm_dD0p1.csv") -> str:
    """Return the text of a standalone .py reproducing the ME runs for `cfgs`.

    All configs must share the same physical setup; only the cooling rate differs.
    """
    c0 = cfgs[0]
    inp = me_inputs_for_solver(c0)
    stem = script_name[:-3] if script_name.endswith(".py") else script_name
    rates = [float(c.rate_K_per_ns) for c in cfgs]
    lam_note = ("" if c0.damping_interpretation == "identity"
                else f"  (LL damping {c0.damping_value:g} converted to Gilbert: a/(1+a^2))")
    subs = {
        "D_NM": f"{c0.d_nm:g}", "T_START": f"{c0.t_start_K:g}", "T_END": f"{c0.t_end_K:g}",
        "DT": f"{c0.dT_grid_K:g}", "B_APP": f"{c0.b_app_T:g}",
        "RATES": "[" + ", ".join(f"{r:g}" for r in rates) + "]",
        "RATES_TXT": ", ".join(f"{r:g}" for r in rates),
        "N_ATOMS": str(int(c0.n_atoms)),
        "A_CELL": f"{c0.cell_a_m:.6g}", "C_CELL": f"{c0.cell_c_m:.6g}",
        "MU_B": f"{MU_B!r}", "MU_S_MUB": f"{c0.mu_s_mub:g}",
        "GAMMA": _g(inp["GAMMA"]), "LAMBDA": f"{inp['LAMBDA']:.10g}", "LAMBDA_NOTE": lam_note,
        "P0": f"{c0.p0:g}",
        "SCRIPT_NAME": script_name, "MODULE": stem,
        "CSV_NAME": f"{stem}.csv", "PNG_NAME": f"{stem}.png",
        "LUT_NAME": lut_name, "VERSION": version or "(unversioned)", "DATE": _dt.date.today().isoformat(),
    }
    text = _TEMPLATE
    for k, v in subs.items():
        text = text.replace(f"@@{k}@@", v)
    text = _align_comments(text)
    assert "@@" not in text, "unfilled template field"
    return text
