#!/usr/bin/env python3
"""
Two-level master equation (ME) for field-cooling a 4 nm FePt grain -- ONE self-contained file.

Case      : linear cooling 800 -> 300 K at 200 K/ns, B = 1.00531 T along the easy axis.
Run       : python3 me_cooling_standalone.py   (writes me_cooling_standalone.csv
            and me_cooling_standalone.png next to this file)
Needs     : numpy, scipy (optional, for Savitzky-Golay smoothing) and the lookup table
            lut_current_rf_1-10nm_dD0p1.csv in this folder.
            No scikit-learn, no pickles, no other .py file.
Optional  : matplotlib for the plot.
            Or from Python:  import me_cooling_standalone as me;  results = me.main();  me.plot(results, show=True)

Roy Chantrell (January 2026) cooling-through-Tc formulation. The temperature-dependent
resonant frequency is omega1(T) = gamma / chi_perp(T), and the escape-rate branches
follow the execution flow in Sections 2.2.4-2.2.5 and pages 6-7 of Roy's report.
The susceptibility normalisation in the RF surrogate must match Roy's stated convention.

Generated by ME Cooling Simulator v1.0 on 2026-11-20.
"""
import csv
import math
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent

# =====================================================================
# 1. INPUTS (edit here)
# =====================================================================
RATES_K_PER_NS = [200]                        # cooling rate(s), K/ns
T_START, T_END, DTEMP = 800, 300, 1           # K
D_NM = 4                                      # grain diameter handed to the surrogate, nm
N_ATOMS = 4602                                # atoms in the grain (geometry calibration)
A_CELL, C_CELL = 2.72e-10, 3.85e-10           # unit cell, m
MU_B = 9.2740100783e-24                       # J/T
MU_S = 3.23 * MU_B                            # atomic moment, 3.23 mu_B
GAMMA = 176085963000.0                        # rad s^-1 T^-1
B_APP = 1.00531                               # applied field, T
LAMBDA = 0.05                                 # damping
P0 = 0.5                                      # initial probability of the "up" state (0.5 = fully disordered)

# derived
CELL_V = A_CELL ** 2 * C_CELL                    # m^3
V_GRAIN = N_ATOMS * CELL_V                       # m^3
MS_0 = MU_S / CELL_V                             # A/m, saturation magnetisation at 0 K
MU0 = 4.0e-7 * math.pi
H_APP = B_APP / MU0                              # A/m

# ---- constants of the model itself ----
KB = 1.380649e-23        # J/K
S_SPIN = 1.5
EPSILON = 1e-12
EXP_MAX = 80.0

LUT_FILE = HERE / "lut_current_rf_1-10nm_dD0p1.csv"
OUT_FILE = HERE / "me_cooling_standalone.csv"
PLOT_FILE = HERE / "me_cooling_standalone.png"
PLOT_DPI = 300                                # CPC requires >=300 dpi for raster

# ---- plot smoothing (Savitzky-Golay) ----
SMOOTH = True          # set False to disable smoothing
SAVGOL_WINDOW = 21     # odd number of samples; auto-clamped to len(T)
SAVGOL_POLY = 3        # polynomial order, must be < SAVGOL_WINDOW

# =====================================================================
# 2. MATERIAL LOOKUP TABLE: m_s(T), chi_par(T), chi_perp(T)  (built from the VAMPIRE-trained surrogate)
# =====================================================================
class FePtML:
    """Bilinear interpolation of the (D, T) table; no random forest needed."""

    def __init__(self):
        self.D = self.T = self.table = None

    def load(self):
        a = np.genfromtxt(LUT_FILE, delimiter=",", names=True)
        self.D = np.unique(a["diameter_nm"])
        self.T = np.unique(a["temperature_K"])
        order = np.lexsort((a["temperature_K"], a["diameter_nm"]))   # D major, T minor
        shape = (len(self.D), len(self.T))
        self.table = np.stack([a[n][order].reshape(shape) for n in ("m_s", "chi_L", "chi_T")])

    def predict(self, D_nm, T):
        """-> m_s, chi_par, chi_perp at diameter D_nm (nm) and temperatures T (K)."""
        T = np.asarray(T, dtype=float)
        if not self.D[0] <= D_nm <= self.D[-1]:
            raise ValueError(f"diameter {D_nm:g} nm outside the table ({self.D[0]:g}-{self.D[-1]:g} nm)")
        if T.min() < self.T[0] or T.max() > self.T[-1]:
            raise ValueError(f"temperature outside the table ({self.T[0]:g}-{self.T[-1]:g} K)")
        i = int(np.clip(np.searchsorted(self.D, D_nm, side="right") - 1, 0, len(self.D) - 2))
        w = (D_nm - self.D[i]) / (self.D[i + 1] - self.D[i])
        row = (1.0 - w) * self.table[:, i, :] + w * self.table[:, i + 1, :]
        return tuple(np.interp(T, self.T, row[k]) for k in range(3))

# =====================================================================
# 3. MASTER-EQUATION PHYSICS
# =====================================================================
def m_eq_field(T, m_s, V, H):
    """Equilibrium magnetisation of the two-level grain in the field: m_s * tanh(mu0 V M_s H / kB T)."""
    arg = (MU0 * V * (MS_0 * m_s) * H) / (KB * T)
    return m_s * np.tanh(np.clip(arg, -50.0, 50.0))

def alpha2_T(T, m_s, Tc):
    """Roy Eq. (5): alpha2 = (lambda/m_e) [tanh(q)/q - T/(3 Tc)]."""
    m_e = max(float(m_s), EPSILON)  # RF surrogate output is reduced magnetisation
    q = max((3.0 * Tc * m_e) / (2.0 * (S_SPIN + 1.0) * T), EPSILON)
    alpha2 = (LAMBDA / m_e) * (np.tanh(q) / q - T / (3.0 * Tc))
    return float(np.clip(alpha2, 1e-6, 0.3))

def escape_rate(T, m_s, chi_L, chi_T, V, Tc, H_appl):
    """Roy's temperature-dependent escape rate, following the report's p. 7 flow."""
    chi_T = max(float(chi_T), EPSILON)
    chi_L = max(float(chi_L), EPSILON)
    m_e = max(float(m_s), EPSILON)

    # Dimensionless Neel barrier: sigma = mu0 Ms(T)^2 V / (2 chi_perp kB T).
    sigma = np.clip((MU0 * (MS_0 * m_e) ** 2 * V) / (2.0 * chi_T * KB * T), 0.0, EXP_MAX)
    r = max(2.0 * chi_L / chi_T, EPSILON)
    alpha2 = alpha2_T(T, m_e, Tc)
    omega1 = GAMMA / chi_T  # Roy Eq. (16), evaluated at each temperature

    if r <= 1.0:
        # Roy report p. 7: field ignored above Tc, field-assisted below Tc.
        if T >= Tc:
            exponent = -sigma * (1.0 - 0.5 * r)
        else:
            H_ratio = MU0 * H_appl * chi_T  # H_appl / H_K, with H_K = 1/(mu0 chi_perp)
            exponent = -sigma * (1.0 - H_ratio) ** 2 * (1.0 - 0.5 * r)
        Gamma = 2.0 * alpha2 * omega1 * np.sqrt(sigma / np.pi) * np.exp(
            np.clip(exponent, -EXP_MAX, EXP_MAX))
    else:
        # Roy report p. 7, precessional/intermediate-to-high damping branch.
        base = (r * sigma / 2.0) * (1.0 - 1.0 / r)
        base = max(float(base), 0.0)
        Gamma0 = (alpha2 * omega1 * np.sqrt(sigma / (np.pi * r)) *
                  np.exp(np.clip(base * (1.0 - 1.0 / r), -EXP_MAX, EXP_MAX)) *
                  math.erfc(np.sqrt(base)))
        F_sad = 1.0 / (4.0 * r)
        Gamma = Gamma0 * np.exp(np.clip(-2.0 * sigma * F_sad, -EXP_MAX, EXP_MAX))

    return max(float(Gamma), 1e-40)

# =====================================================================
# 4. RUN: integrate P(t) (probability of the "up" state) along the cooling ramp
# =====================================================================
def run_rate(ml, rate):
    """One cooling run at `rate` K/ns -> (T, m, P, m_s, Tc)."""
    T = np.arange(T_START, T_END - DTEMP, -DTEMP)
    n = len(T)
    m_s_arr, chi_L_arr, chi_T_arr = ml.predict(D_NM, T)
    Tc = float(T[np.argmax(chi_L_arr)])                  # Curie temperature: peak of chi_par(T)
    dt = DTEMP / (rate * 1e9)                            # time per step, s

    P = np.zeros(n)
    m = np.zeros(n)
    P[0] = P0
    m[0] = np.clip(m_s_arr[0] * (2.0 * P[0] - 1.0), 0.0, m_s_arr[0])

    for i in range(n - 1):
        Gamma = escape_rate(T[i], m_s_arr[i], chi_L_arr[i], chi_T_arr[i], V_GRAIN, Tc, H_APP)
        m_eq_next = m_eq_field(T[i + 1], m_s_arr[i + 1], V_GRAIN, H_APP)
        P_eq_next = np.clip(0.5 * (1.0 + m_eq_next / max(m_s_arr[i + 1], EPSILON)), 0.0, 1.0)
        # master-equation step: P relaxes towards P_eq with rate Gamma
        P[i + 1] = np.clip(P_eq_next + (P[i] - P_eq_next) * np.exp(-Gamma * dt), 0.0, 1.0)
        m[i + 1] = np.clip(m_s_arr[i + 1] * (2.0 * P[i + 1] - 1.0), 0.0, m_s_arr[i + 1])
    return T, m, P, m_s_arr, Tc

def main():
    ml = FePtML()
    ml.load()
    results = []
    for rate in RATES_K_PER_NS:
        T, m, P, m_s_arr, Tc = run_rate(ml, rate)
        print(f"rate={rate:g} K/ns  Tc={Tc:g} K  m({T[-1]:g} K)={m[-1]:.4f}  "
              f"m/ms={m[-1] / m_s_arr[-1]:.4f}")
        results.append((rate, T, m, P, m_s_arr, Tc))

    with open(OUT_FILE, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["rate_K_per_ns", "T_K", "m", "P_up", "m_s"])
        for rate, T, m, P, m_s_arr, _ in results:
            w.writerows([rate, *row] for row in zip(T, m, P, m_s_arr))
    print(f"data -> {OUT_FILE.name}")
    return results

