# 5. PLOT (matplotlib optional) — CPC-journal academic style
# =====================================================================
def _savgol(y, window=SAVGOL_WINDOW, poly=SAVGOL_POLY):
    """Savitzky-Golay smoothing; falls back to raw data if SciPy is missing
    or the window is invalid for the array length."""
    if not SMOOTH:
        return y
    try:
        from scipy.signal import savgol_filter
    except ImportError:
        print("scipy not installed -> smoothing skipped")
        return y
    n = len(y)
    w = min(window, n if n % 2 == 1 else n - 1)   # force odd, <= n
    p = min(poly, w - 1)
    if w < 3 or p < 1:
        return y
    return savgol_filter(y, window_length=w, polyorder=p, mode="interp")


def plot(results, out=PLOT_FILE, show=False):
    """Plot m(T) for every rate in a clean publication-ready style; save PNG only."""
    try:
        import matplotlib
        if not show:
            matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        from matplotlib.ticker import AutoMinorLocator, MultipleLocator
    except ImportError:
        print("matplotlib not installed -> plot skipped")
        return

    # ---- Publication-quality Matplotlib style (PNG only) ----
    rc = {
        "font.family": "sans-serif",
        "font.sans-serif": ["Arial", "Helvetica", "DejaVu Sans"],
        "font.size": 10,
        "axes.labelsize": 11,
        "axes.titlesize": 11,
        "axes.linewidth": 0.9,
        "axes.labelpad": 6,
        # Full four-sided plot frame, as commonly used for CPC figures.
        "axes.spines.top": True,
        "axes.spines.right": True,
        "xtick.direction": "out",
        "ytick.direction": "out",
        "xtick.major.size": 4,
        "ytick.major.size": 4,
        "xtick.minor.size": 2,
        "ytick.minor.size": 2,
        "xtick.major.width": 0.8,
        "ytick.major.width": 0.8,
        "xtick.minor.width": 0.6,
        "ytick.minor.width": 0.6,
        "xtick.labelsize": 9,
        "ytick.labelsize": 9,
        "legend.fontsize": 9,
        "legend.frameon": False,
        "legend.handlelength": 2.4,
        "legend.handletextpad": 0.6,
        "legend.labelspacing": 0.45,
        "lines.solid_capstyle": "round",
        "savefig.dpi": PLOT_DPI,
        "savefig.bbox": "tight",
        "savefig.pad_inches": 0.08,
        "figure.dpi": 160,
        "mathtext.fontset": "dejavusans",
    }

    with matplotlib.rc_context(rc):
        # Wider landscape layout improves readability in papers and presentations.
        fig, ax = plt.subplots(figsize=(5.6, 4.0), constrained_layout=True)
        fig.patch.set_facecolor("white")
        ax.set_facecolor("white")

        # Ensure a complete, uniform four-sided frame (top/right included).
        for spine in ax.spines.values():
            spine.set_visible(True)
            spine.set_linewidth(0.9)
            spine.set_color("#222222")

        # Show inward ticks on all four sides, matching the framed axes.
        ax.tick_params(
            axis="both", which="both",
            direction="in", top=True, right=True,
        )

        # Colour-blind-friendly Okabe-Ito palette.
        palette = ["#0072B2", "#D55E00", "#009E73", "#CC79A7",
                   "#E69F00", "#56B4E9", "#000000"]

        for k, (rate, T, m, _, _, _) in enumerate(results):
            c = palette[k % len(palette)]

            # Keep the unsmoothed numerical result visible, but visually secondary.
            ax.plot(T, m, color=c, lw=0.85, alpha=0.24,
                    solid_capstyle="round", zorder=2)

            # Smoothed trace is a visual guide; raw data remain available above.
            m_smooth = _savgol(m)
            ax.plot(T, m_smooth, color=c, lw=2.2,
                    label=rf"{rate:g} K/ns", zorder=3)

        # Curie temperature marker and compact annotation.
        Tc = results[0][5]
        ax.axvline(Tc, color="#444444", lw=1.1, ls=(0, (4, 3)), zorder=1)
        ax.annotate(
            rf"$T_{{\mathrm{{C}}}} = {Tc:.0f}\,\mathrm{{K}}$",
            xy=(Tc, 0.97), xycoords=("data", "axes fraction"),
            xytext=(7, -2), textcoords="offset points",
            ha="left", va="top", fontsize=9, color="#333333",
            bbox=dict(boxstyle="round,pad=0.22", fc="white", ec="none", alpha=0.88),
        )

        ax.set_xlabel(r"Temperature, $T$ (K)")
        ax.set_ylabel(r"Reduced magnetisation, $m_z$")
        ax.set_xlim(T_START, T_END)  # Cooling direction: high T on the left.
        ax.set_ylim(0.0, 1.04)

        ax.xaxis.set_major_locator(MultipleLocator(100))
        ax.xaxis.set_minor_locator(AutoMinorLocator(2))
        ax.yaxis.set_major_locator(MultipleLocator(0.2))
        ax.yaxis.set_minor_locator(AutoMinorLocator(2))

        # Restrained horizontal guides aid reading without competing with the data.
        ax.grid(axis="y", which="major", color="#D9DDE2", lw=0.65, alpha=0.75)
        ax.grid(axis="y", which="minor", color="#ECEFF2", lw=0.45, alpha=0.8)
        ax.set_axisbelow(True)
        ax.tick_params(which="both", direction="in", top=True, right=True)
        ax.margins(x=0.01)

        # Legend outside the data region when multiple rates are present.
        ax.legend(
            loc="lower right",
            title="Cooling rate",
            title_fontsize=9,
            ncol=1,
            frameon=True,
            facecolor="white",
            edgecolor="none",
            framealpha=0.92,
        )

        out = Path(out).with_suffix(".png")
        fig.savefig(out, dpi=PLOT_DPI, facecolor="white")
        print(f"plot -> {out.name} ({PLOT_DPI} dpi, PNG only)")

        if show:
            plt.show()
        plt.close(fig)

if __name__ == "__main__":
    plot(main(), show=True)
